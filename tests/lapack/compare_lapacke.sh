#!/usr/bin/env bash
# Compares hwyBLAS's LAPACKE functions with the reference LAPACKE (see
# compare_lapacke.cc). Run by hand; not part of the build or of ctest.
#
#   tests/lapack/compare_lapacke.sh <hwyblas build dir> <reference build dir> \
#       <work dir> [jobs] [seed]
#
# <reference build dir> is a build of the reference LAPACK with
# -DBUILD_SHARED_LIBS=ON -DLAPACKE=ON, with hwyBLAS as its BLAS, without
# floating-point contraction and with an XERBLA that returns (as
# compare_reference.sh builds LAPACK; on Windows also
# -DCMAKE_WINDOWS_EXPORT_ALL_SYMBOLS=ON). CXX selects the compiler. The
# output of each function that differs is in <work dir>/results.txt.
#
# With RECORD=tests/lapack/lapacke_checks.inc, it writes that file instead
# (the calls that lapacke_validation_test.cc repeats), and the calls where
# hwyBLAS differs from the reference to <work dir>/record_differences.txt.
set -euo pipefail

if [ $# -lt 3 ]; then
  sed -n '2,18p' "$0"
  exit 1
fi
hwy_build=$(cd "$1" && pwd)
ref_build=$(cd "$2" && pwd)
mkdir -p "$3"
work=$(cd "$3" && pwd)
jobs=${4:-8}
seed=${5:-1}
here=$(cd "$(dirname "$0")" && pwd)

case "$(uname -s)" in
  MINGW* | MSYS* | CYGWIN*)
    native() { cygpath -m "$1"; }
    hwy_shared=$hwy_build/bin/hwyblas.dll
    lapacke=liblapacke.dll lapack=liblapack.dll
    exe=.exe
    ;;
  Darwin)
    native() { echo "$1"; }
    hwy_shared=$hwy_build/lib/libhwyblas.dylib
    lapacke=liblapacke.dylib lapack=liblapack.dylib
    exe=
    ;;
  *)
    native() { echo "$1"; }
    hwy_shared=$hwy_build/lib/libhwyblas.so
    lapacke=liblapacke.so lapack=liblapack.so
    exe=
    ;;
esac
find_lib() { find "$ref_build" -name "$1" | head -1; }
ref_lapacke=$(find_lib "$lapacke")
ref_lapack=$(find_lib "$lapack")
[ -n "$ref_lapacke" ] && [ -n "$ref_lapack" ] ||
  { echo "No reference LAPACKE in $ref_build" >&2; exit 1; }
# The reference libraries find each other and hwyBLAS.
export PATH="$(dirname "$ref_lapacke"):$(dirname "$hwy_shared"):$PATH"

mkdir -p "$work/src"
header=$here/../../include/hwyblas/lapacke.h
grep -ohE '\bLAPACKE_[a-z0-9_]+ *\(' "$header" | sed -E 's/ *\($//' |
  grep -vE '^LAPACKE_(xerbla|set_nancheck|get_nancheck|xyyzzz(_work)?)$' | sort -u |
  sed 's/.*/X(&)/' > "$work/src/lapacke_names.inc"
cat > "$work/src/CMakeLists.txt" <<EOT
cmake_minimum_required(VERSION 3.20)
project(compare_lapacke CXX)
set(CMAKE_CXX_STANDARD 17)
add_executable(compare_lapacke "$(native "$here/compare_lapacke.cc")")
target_include_directories(compare_lapacke PRIVATE "$(native "$work/src")"
  "$(native "$here/../../include")" "$(native "$here/../../bench")")
if(MSVC)
  target_compile_options(compare_lapacke PRIVATE /bigobj)
endif()
find_package(Threads REQUIRED)
target_link_libraries(compare_lapacke PRIVATE \${CMAKE_DL_LIBS} Threads::Threads)
EOT
cmake -S "$work/src" -B "$work/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  ${CXX:+"-DCMAKE_CXX_COMPILER=$CXX"} > "$work/build.log"
cmake --build "$work/build" >> "$work/build.log" ||
  { grep -E -m20 'error' "$work/build.log" >&2; exit 1; }

export CL_TOOL="$work/build/compare_lapacke$exe"
export CL_ARGS="$(native "$hwy_shared")|$(native "$ref_lapacke")|$(native "$ref_lapack")|$(native "$header")"
export CL_OUT="$work/out" CL_SEED="$seed"
rm -rf "$CL_OUT"
mkdir -p "$CL_OUT"
one() {
  IFS='|' read -r -a args <<< "$CL_ARGS"
  local code=0
  timeout 300 "$CL_TOOL" "${args[@]}" run "$1" "seed=$CL_SEED" \
    > "$CL_OUT/$1.txt" 2>/dev/null || code=$?
  echo "$code" > "$CL_OUT/$1.code"
}
export -f one
IFS='|' read -r -a args <<< "$CL_ARGS"
"$CL_TOOL" "${args[@]}" list 2> "$work/missing.txt" | tr -d '\r' > "$work/list.txt"
echo "$(wc -l < "$work/list.txt") functions"

if [ -n "${RECORD:-}" ]; then
  record() {
    IFS='|' read -r -a args <<< "$CL_ARGS"
    local code=0
    timeout 300 "$CL_TOOL" "${args[@]}" record "$1" \
      > "$CL_OUT/$1.rows" 2> "$CL_OUT/$1.diff" || code=$?
    [ "$code" = 0 ] || echo "$1: exit $code" >> "$CL_OUT/$1.diff"
  }
  export -f record
  xargs -P "$jobs" -n 1 bash -c 'record "$0"' < "$work/list.txt"
  {
    echo "// Calls and what the reference LAPACKE 3.12.1 returns for them, for"
    echo "// lapacke_validation_test.cc: the function, its arguments other than"
    echo "// arrays, the argument with a NaN (or -1), the element with it (or -1:"
    echo "// all of an array), whether in the imaginary part, the arrays that are"
    echo "// null pointers (bit k: argument k), the return value and the message."
    echo "// Generated by compare_lapacke.sh; do not edit."
    echo "// clang-format off"
    while read -r name; do
      # Complete rows only (a crash can cut the last one off).
      tr -d '\r' < "$CL_OUT/$name.rows" | grep '},$' || true
    done < "$work/list.txt"
  } > "$RECORD"
  while read -r name; do cat "$CL_OUT/$name.diff"; done < "$work/list.txt" \
    | tr -d '\r' > "$work/record_differences.txt"
  echo "$(grep -c '^{' "$RECORD") rows in $RECORD," \
    "$(wc -l < "$work/record_differences.txt") differences"
  exit 0
fi
xargs -P "$jobs" -n 1 bash -c 'one "$0"' < "$work/list.txt"

: > "$work/results.txt"
failed=0
while read -r name; do
  code=$(cat "$CL_OUT/$name.code")
  if [ "$code" != 0 ]; then
    failed=$((failed + 1))
    { echo "== $name: exit $code"; tail -30 "$CL_OUT/$name.txt"; } >> "$work/results.txt"
  fi
done < "$work/list.txt"
echo "$failed functions differ or failed, see $work/results.txt"
[ "$failed" = 0 ]
