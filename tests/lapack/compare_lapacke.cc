// One call

std::mt19937_64 rng;

// An array is passed as a pointer into the middle of its buffer: routines
// without argument checks reach before it for a negative dimension. The
// margin is a multiple of 17 elements, for the identity fill.
constexpr size_t kMargin = 17 * 16 * 256;
constexpr size_t kBufferBytes = 4096 * 32 + 2 * kMargin;
constexpr int kStyles = 4;

const char kChars[] = "NUTLCVASORBEPQGIDFHKXM1Znutlcvas?";
const long long kDimensions[] = {-1, 0, 1, 2, 3, 4, 5, 6, 8, 9};
const long long kLeadings[] = {-1, 0, 1, 2, 3, 4, 5, 6, 8, 9, 16};
const long long kWorkspaces[] = {-1, 0,  1,  2,   3,   5,   9,
                                 17, 33, 65, 129, 257, 513, 2048};
const double kReals[] = {0.5, 1, 0, -1, 2, -10, 10, 3};

struct Call {
  const Routine* routine;
  std::vector<Slot> values;  // all but the pointers
  std::vector<int> styles;   // the fill of each array
  uint64_t fill_seed = 1;
  uint64_t nulls = 0;     // the arrays passed as null pointers (bit k)
  int nan_param = -1;     // the argument with a NaN
  long nan_element = -1;  // -1: all of the array
  bool nan_imaginary = false;
};

// The contents of an array: 0 random in [-1, 1], 1 diagonally dominant (for
// the leading dimension ld), 2 ones, 3 random in [0.5, 1.5]; integers are
// 1, 2, 3, ... from where the pointer passed to the function points (pivot
// indices, IFST and ILST).
std::vector<unsigned char> Fill(const Param& p, int style, uint64_t seed,
                                long long ld) {
  std::vector<unsigned char> b(kBufferBytes, 0);
  std::mt19937_64 g(seed);
  std::uniform_real_distribution<double> d(-1, 1), positive(0.5, 1.5);
  const size_t count = kBufferBytes / p.real;
  for (size_t i = 0; i < count; ++i) {
    if (p.integers) {
      const long long x = static_cast<long long>(i) -
                          static_cast<long long>(kMargin / p.real) + 1;
      memcpy(&b[i * p.real], &x, p.real);
      continue;
    }
    const size_t e = i / static_cast<size_t>(p.parts);
    const bool imaginary = i % static_cast<size_t>(p.parts) != 0;
    double v = 0;
    switch (style) {
      case 0:
        v = d(g);
        break;
      case 1: {
        const long long from_pointer =
            static_cast<long long>(e) -
            static_cast<long long>(kMargin / p.real) / p.parts;
        v = 0.02 * d(g);
        if (from_pointer % (std::max<long long>(ld, 1) + 1) == 0) {
          v = imaginary ? 0 : 2 + positive(g);
        }
        break;
      }
      case 2:
        v = imaginary ? 0 : 1;
        break;
      default:
        v = positive(g);
        break;
    }
    if (p.real == 4) {
      const float x = static_cast<float>(v);
      memcpy(&b[i * 4], &x, 4);
    } else {
      memcpy(&b[i * 8], &v, 8);
    }
  }
  return b;
}

void PutNan(std::vector<unsigned char>& b, const Param& p, size_t index) {
  if (p.real == 4) {
    const float x = std::numeric_limits<float>::quiet_NaN();
    memcpy(&b[index * 4], &x, 4);
  } else {
    const double x = std::numeric_limits<double>::quiet_NaN();
    memcpy(&b[index * 8], &x, 8);
  }
}

// The leading dimension of array k: the argument "ld" + its name, or 16.
long long LeadingOf(const Call& call, size_t k) {
  const Routine& r = *call.routine;
  for (size_t j = 0; j < r.params.size(); ++j) {
    if (r.params[j].name == "ld" + r.params[k].name) return call.values[j].i;
  }
  return 16;
}

std::vector<unsigned char> FillArgument(const Call& call, size_t k) {
  return Fill(call.routine->params[k], call.styles[k],
              call.fill_seed * 1000 + k, LeadingOf(call, k));
}

std::string Describe(const Call& call) {
  const Routine& r = *call.routine;
  std::string s;
  char num[40];
  for (size_t k = 0; k < r.params.size(); ++k) {
    const Param& p = r.params[k];
    if (p.kind == Kind::kArray || p.kind == Kind::kCallback) continue;
    if (!s.empty()) s += " ";
    s += p.name + "=";
    if (p.kind == Kind::kChar) {
      s += std::string(1, call.values[k].c);
    } else if (p.kind == Kind::kReal || p.kind == Kind::kComplex) {
      snprintf(num, sizeof(num), "%g", call.values[k].d);
      s += num;
    } else {
      s += std::to_string(call.values[k].i);
    }
  }
  if (call.nan_param >= 0) {
    s += " [NaN in " + r.params[call.nan_param].name;
    if (call.nan_element >= 0) {
      s += "[" + std::to_string(call.nan_element) + "]";
      if (call.nan_imaginary) s += ".imag";
    }
    s += "]";
  }
  return s;
}

