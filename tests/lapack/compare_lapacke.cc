// Compares the LAPACKE functions with the reference LAPACKE's, loading the
// libraries at runtime:
//
//   compare_lapacke <hwyblas library> <reference liblapacke>
//                   <reference liblapack> <lapacke.h> list
//   compare_lapacke <hwyblas library> <reference liblapacke>
//                   <reference liblapack> <lapacke.h> run <function>...
//                   [seed=N]
//   compare_lapacke <hwyblas library> <reference liblapacke>
//                   <reference liblapack> <lapacke.h> record <function>...
//
// "record" prints rows of tests/lapack/lapacke_checks.inc, with the return
// value and message that the reference gives: calls that it rejects, because
// of a NaN in an argument or a leading dimension that is too small, and
// workspace queries with null pointers for the arrays that it does not
// reference in them.
// lapacke_validation_test.cc repeats them without the reference. A call for
// which hwyBLAS differs (a documented deviation) is not recorded, but printed
// on standard error.
//
// A call is generated from the declaration in lapacke.h. A valid one is found
// as in compare_arguments.cc: the arguments that the reference reports as
// invalid (-k) are changed until it accepts the call. Starting from several
// valid calls (in both layouts), four things are compared, each with the
// reference as the oracle:
//  - layout: the return value and the LAPACKE_xerbla message for an invalid
//    matrix_layout;
//  - arguments: the same for calls with one to three characters or integers
//    (dimensions, leading dimensions, workspace sizes) changed to random
//    values, valid or not;
//  - nan: the same for calls with a NaN in one argument: in a whole array, in
//    one of its elements (which tests the part of a matrix that is checked),
//    or in a scalar. Not for the _work functions, which check nothing;
//  - values: the return value and every array after valid calls whose leading
//    dimensions all differ. Elements that no routine writes must keep their
//    contents; the others may differ by rounding. Work arrays are only
//    compared in workspace queries (their first element).
//
// Differences are not always errors: see doc/deviations.md, and note that a
// row-major call copies uninitialized parts of its temporaries back where the
// routine writes only part of a matrix.
//
// The list of functions (lapacke_names.inc, X(name) for every function of
// lapacke.h) is generated by compare_lapacke.sh. Run one process per function:
// a call can crash or corrupt the heap, and one that takes longer than 20
// seconds ends the program with exit code 3. COMPARE_LAPACKE_TRACE=1 prints
// each call before it runs. Not part of the build or of ctest.
//
