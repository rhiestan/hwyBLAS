enum class Kind { kLayout, kChar, kInt, kReal, kComplex, kArray, kCallback };
enum class IntClass { kDimension, kLeading, kWorkspace };

struct Param {
  std::string name;
  Kind kind = Kind::kArray;
  IntClass int_class = IntClass::kDimension;
  // Arrays: the size of a real number (or integer) and how many make an
  // element; whether the function may write it; whether it is scratch space.
  size_t real = 8;
  int parts = 1;
  bool integers = false;
  bool constant = false;
  bool scratch = false;
};

struct Routine {
  std::string name;
  std::vector<Param> params;
  bool work_function = false;
  bool has_layout = false;
};

std::vector<Routine> ParseHeader(const std::string& path) {
  std::ifstream in(path);
  std::stringstream text;
  text << in.rdbuf();
  const std::string raw = text.str();
  std::string s;
  for (size_t i = 0; i < raw.size();) {
    if (raw.compare(i, 2, "/*") == 0) {
      const size_t e = raw.find("*/", i + 2);
      i = e == std::string::npos ? raw.size() : e + 2;
      s += ' ';
    } else {
      s += raw[i++];
    }
  }
  std::vector<Routine> routines;
  for (size_t pos = s.find("HWYBLAS_API"); pos != std::string::npos;
       pos = s.find("HWYBLAS_API", pos + 1)) {
    const size_t open = s.find('(', pos), semicolon = s.find(';', pos);
    if (open == std::string::npos || semicolon == std::string::npos ||
        open > semicolon) {
      continue;
    }
    const size_t close = s.rfind(')', semicolon);
    std::stringstream head(s.substr(pos + 11, open - pos - 11));
    std::string word, name;
    while (head >> word) name = word;
    if (name.rfind("LAPACKE_", 0) != 0) continue;
    Routine r;
    r.name = name;
    r.work_function =
        name.size() > 5 && name.compare(name.size() - 5, 5, "_work") == 0;
    std::stringstream params(s.substr(open + 1, close - open - 1));
    std::string p;
    while (std::getline(params, p, ',')) {
      std::stringstream words(p);
      std::vector<std::string> w;
      while (words >> word) w.push_back(word);
      if (w.size() < 2) continue;
      Param q;
      q.name = w.back();
      std::string type;
      for (size_t i = 0; i + 1 < w.size(); ++i) type += w[i] + " ";
      while (!q.name.empty() && q.name[0] == '*') {
        type += "*";
        q.name.erase(0, 1);
      }
      const auto has = [&type](const char* t) {
        return type.find(t) != std::string::npos;
      };
      const bool pointer = has("*");
      q.constant = has("const ");
      if (q.name == "matrix_layout" || q.name == "matrix_order") {
        q.kind = Kind::kLayout;
        r.has_layout = true;
      } else if (has("SELECT")) {
        q.kind = Kind::kCallback;
      } else if (pointer) {
        q.kind = Kind::kArray;
        if (has("complex_float")) {
          q.real = 4;
          q.parts = 2;
        } else if (has("complex_double")) {
          q.real = 8;
          q.parts = 2;
        } else if (has("float")) {
          q.real = 4;
        } else if (has("double")) {
          q.real = 8;
        } else if (has("char")) {
          q.real = 1;
          q.integers = true;
        } else {
          q.real = sizeof(lapack_int);
          q.integers = true;
        }
        for (const char* n :
             {"work", "rwork", "iwork", "swork", "bwork", "dwork"}) {
          if (q.name == n) q.scratch = true;
        }
      } else if (has("complex")) {
        q.kind = Kind::kComplex;
      } else if (has("float") || has("double")) {
        q.kind = Kind::kReal;
      } else if (has("char")) {
        q.kind = Kind::kChar;
      } else {
        q.kind = Kind::kInt;
        if (q.name.rfind("ld", 0) == 0) {
          q.int_class = IntClass::kLeading;
        } else if (q.name.size() > 1 && q.name[0] == 'l' &&
                   q.name.find("work") != std::string::npos) {
          q.int_class = IntClass::kWorkspace;
        }
      }
      r.params.push_back(q);
    }
    routines.push_back(std::move(r));
  }
  return routines;
}

