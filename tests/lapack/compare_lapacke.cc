// Comparisons

bool Same(double x, double y) {
  return x == y || (std::isnan(x) && std::isnan(y));
}

// The first difference between the arrays of two outcomes, or "".
// Elements that differ between the reference's outcomes y and again are
// undefined and skipped.
std::string ArrayDifference(const Call& call, const Outcome& x,
                            const Outcome& y, const Outcome& again) {
  const Routine& r = *call.routine;
  bool query = false;
  for (size_t k = 0; k < r.params.size(); ++k) {
    if (r.params[k].kind == Kind::kInt &&
        r.params[k].int_class == IntClass::kWorkspace &&
        call.values[k].i == -1) {
      query = true;
    }
  }
  for (size_t k = 0; k < r.params.size(); ++k) {
    const Param& p = r.params[k];
    if (p.kind != Kind::kArray) continue;
    size_t count = kBufferBytes / p.real;
    if (p.scratch) {
      if (!query) continue;
      count = 1;
    }
    const std::vector<unsigned char> start = FillArgument(call, k);
    for (size_t i = 0; i < count; ++i) {
      const unsigned char* a = &x.arrays[k][i * p.real];
      const unsigned char* b = &y.arrays[k][i * p.real];
      if (memcmp(a, b, p.real) == 0) continue;
      if (memcmp(b, &again.arrays[k][i * p.real], p.real) != 0) continue;
      double u = 0, v = 0;
      if (p.integers) {
        long long s = 0, t = 0;
        memcpy(&s, a, p.real);
        memcpy(&t, b, p.real);
        u = static_cast<double>(s);
        v = static_cast<double>(t);
      } else if (p.real == 4) {
        float s, t;
        memcpy(&s, a, 4);
        memcpy(&t, b, 4);
        u = s;
        v = t;
      } else {
        memcpy(&u, a, 8);
        memcpy(&v, b, 8);
      }
      // Rounding: only where both wrote the element.
      const bool written_by_both = memcmp(a, &start[i * p.real], p.real) != 0 &&
                                   memcmp(b, &start[i * p.real], p.real) != 0;
      if (!p.integers && written_by_both) {
        const double tolerance = p.real == 4 ? 2e-3 : 1e-9;
        if (Same(u, v) ||
            std::abs(u - v) <=
                tolerance * std::max({1.0, std::abs(u), std::abs(v)})) {
          continue;
        }
      }
      char text[200];
      snprintf(text, sizeof(text), "%s[%td]%s: %.9g, reference %.9g%s",
               p.name.c_str(),
               (static_cast<ptrdiff_t>(i) -
                static_cast<ptrdiff_t>(kMargin / p.real)) /
                   p.parts,
               p.parts == 2 && i % 2 ? ".imag" : "", u, v,
               written_by_both ? "" : " (not written by both)");
      return text;
    }
  }
  return "";
}

struct Category {
  const char* name;
  int calls = 0;
  int mismatches = 0;
};

bool UndefinedResult(const Call& call) {
  const Routine& r = *call.routine;
  if (r.name.size() < 13 || r.name.compare(9, 3, "lan") != 0) return false;
  for (size_t k = 0; k < r.params.size(); ++k) {
    const std::string& n = r.params[k].name;
    const char* valid = n == "norm"   ? "MmOoIiFfEe1"
                        : n == "uplo" ? "UuLl"
                        : n == "diag" ? "UuNn"
                                      : nullptr;
    if (valid != nullptr && strchr(valid, call.values[k].c) == nullptr) {
      return true;
    }
  }
  return false;
}

// INFO is compared exactly, a norm up to rounding.
bool SameResult(double x, double y) {
  if (Same(x, y)) return true;
  if (x == std::floor(x) && y == std::floor(y)) return false;
  return std::abs(x - y) <= 2e-3 * std::max(1.0, std::abs(y));
}

void Compare(Runner& runner, const Call& call, bool values,
             Category& category) {
  if (UndefinedResult(call)) return;
  const Outcome y = runner.Execute(runner.ref, call);
  if (y.crashed) return;  // no oracle
  // A negative leading dimension that the reference does not reject, in
  // column-major layout: the routine has no argument checks, and what it reads
  // is undefined.
  const bool column_major =
      !call.routine->has_layout || call.values[0].i == LAPACK_COL_MAJOR;
  for (size_t k = 0; k < call.routine->params.size(); ++k) {
    const Param& p = call.routine->params[k];
    if (column_major && p.kind == Kind::kInt &&
        p.int_class == IntClass::kLeading && call.values[k].i < 0 &&
        !(y.result < 0 && y.result == std::floor(y.result))) {
      return;
    }
  }
  const Outcome x = runner.Execute(runner.hwy, call);
  ++category.calls;
  std::string difference;
  if (x.crashed) {
    difference =
        "hwyBLAS crashed, the reference returned " + std::to_string(y.result);
  } else if (!SameResult(x.result, y.result)) {
    char text[100];
    snprintf(text, sizeof(text), "returned %.17g, reference %.17g", x.result,
             y.result);
    difference = text;
  } else if (x.message != y.message) {
    difference =
        "message \"" + x.message + "\", reference \"" + y.message + "\"";
  } else if (values) {
    // After INFO > 0, a Cholesky factorization leaves its matrix partly
    // factored, in a way that depends on the blocking.
    const bool partial =
        y.result > 0 && call.routine->name.compare(9, 2, "po") == 0;
    if (!partial) difference = ArrayDifference(call, x, y, y);
  }
  if (difference.empty()) return;
  // Undefined if the reference does not repeat itself.
  const Outcome again = runner.Execute(runner.ref, call);
  if (again.crashed || !SameResult(again.result, y.result)) return;
  if (values && !x.crashed && SameResult(x.result, y.result) &&
      x.message == y.message) {
    difference = ArrayDifference(call, x, y, again);
    if (difference.empty()) return;
  }
  if (++category.mismatches <= 4) {
    printf("%s [%s] %s\n    %s\n", call.routine->name.c_str(), category.name,
           difference.c_str(), Describe(call).c_str());
  }
}

int Run(Runner& runner, const Routine& r, unsigned seed) {
  if (!runner.hwy.Find(r.name.c_str()) || !runner.ref.Find(r.name.c_str())) {
    printf("%s: not in both libraries\n", r.name.c_str());
    return 0;
  }
  rng.seed(seed);
  Category layout{"layout"}, arguments{"arguments"}, nan{"nan"},
      values{"values"};
  int bases[2] = {0, 0};
  const int layouts = r.has_layout ? 2 : 1;
  for (int l = 0; l < layouts; ++l) {
    const int matrix_layout = l == 0 ? LAPACK_COL_MAJOR : LAPACK_ROW_MAJOR;
    for (int base = 0; base < 24; ++base) {
      Call valid{&r};
      if (!FindValid(runner, matrix_layout, valid)) continue;
      ++bases[l];
      // Values, with the leading dimensions of the search and distinct ones.
      Compare(runner, valid, true, values);
      Call distinct = valid;
      DistinctLeadingDimensions(runner, distinct);
      Compare(runner, distinct, true, values);
      // A workspace query.
      Call query = distinct;
      bool has_query = false;
      for (size_t k = 0; k < r.params.size(); ++k) {
        if (r.params[k].kind == Kind::kInt &&
            r.params[k].int_class == IntClass::kWorkspace) {
          query.values[k].i = -1;
          has_query = true;
        }
      }
      if (has_query) {
        Compare(runner, query, true, values);
        // Each size alone.
        for (size_t k = 0; k < r.params.size(); ++k) {
          if (r.params[k].kind != Kind::kInt ||
              r.params[k].int_class != IntClass::kWorkspace) {
            continue;
          }
          Call one = distinct;
          one.values[k].i = -1;
          Compare(runner, one, true, values);
        }
      }
      // Invalid layouts.
      if (r.has_layout && base < 6) {
        for (const int bad : {0, 100, 103, -1}) {
          Call call = distinct;
          call.values[0].i = bad;
          Compare(runner, call, false, layout);
        }
      }
      // Changed characters and integers.
      for (int t = 0; t < 60; ++t) {
        Call call = t % 2 ? valid : distinct;
        const int changes = 1 + static_cast<int>(rng() % 3);
        for (int c = 0; c < changes; ++c) {
          const size_t k = rng() % r.params.size();
          const Param& p = r.params[k];
          if (p.kind == Kind::kChar) {
            call.values[k].c = kChars[rng() % (sizeof(kChars) - 1)];
          } else if (p.kind == Kind::kInt) {
            if (p.int_class == IntClass::kLeading) {
              call.values[k].i = kLeadings[rng() % std::size(kLeadings)];
            } else if (p.int_class == IntClass::kWorkspace) {
              call.values[k].i = kWorkspaces[rng() % std::size(kWorkspaces)];
            } else {
              call.values[k].i = kDimensions[rng() % std::size(kDimensions)];
            }
          }
        }
        Compare(runner, call, false, arguments);
      }
      // NaNs.
      if (!r.work_function && base < 8) {
        for (size_t k = 0; k < r.params.size(); ++k) {
          const Param& p = r.params[k];
          const bool array = p.kind == Kind::kArray && !p.integers;
          const bool scalar = p.kind == Kind::kReal || p.kind == Kind::kComplex;
          if (!array && !scalar) continue;
          Call call = base % 2 ? valid : distinct;
          call.nan_param = static_cast<int>(k);
          Compare(runner, call, false, nan);
          if (scalar) {
            if (p.kind == Kind::kComplex) {
              call.nan_imaginary = true;
              Compare(runner, call, false, nan);
            }
            continue;
          }
          for (int t = 0; t < 40; ++t) {
            call.nan_element =
                static_cast<long>(t < 12 ? t : rng() % (t < 30 ? 60 : 160));
            call.nan_imaginary = p.parts == 2 && rng() % 2;
            Compare(runner, call, false, nan);
          }
        }
      }
    }
  }
  const int mismatches = layout.mismatches + arguments.mismatches +
                         nan.mismatches + values.mismatches;
  printf(
      "%s: valid %d+%d; layout %d/%d, arguments %d/%d, nan %d/%d, values %d/%d "
      "mismatches\n",
      r.name.c_str(), bases[0], bases[1], layout.mismatches, layout.calls,
      arguments.mismatches, arguments.calls, nan.mismatches, nan.calls,
      values.mismatches, values.calls);
  fflush(stdout);
  return mismatches ? 1 : 0;
}

// The values of the arguments that are not arrays, as the test reads them.
std::string Scalars(const Call& call) {
  const Routine& r = *call.routine;
  std::string s;
  char num[40];
  for (size_t k = 0; k < r.params.size(); ++k) {
    const Kind kind = r.params[k].kind;
    if (kind == Kind::kArray || kind == Kind::kCallback) continue;
    if (!s.empty()) s += " ";
    if (kind == Kind::kChar) {
      s += std::string(1, call.values[k].c);
    } else if (kind == Kind::kReal || kind == Kind::kComplex) {
      snprintf(num, sizeof(num), "%g", call.values[k].d);
      s += num;
    } else {
      s += std::to_string(call.values[k].i);
    }
  }
  return s;
}

class Recorder {
 public:
  Recorder(Runner& runner, const Routine& r) : runner_(runner), r_(r) {}

  // Runs the call in the reference; if it rejects it and no row has the key
  // yet, records it. Returns whether the reference rejected it.
  bool Try(const Call& call, const std::string& key) {
    const Outcome y = runner_.Execute(runner_.ref, call);
    // A rejected call returns a negative argument position; a workspace
    // query (with null pointers) succeeds.
    const bool query = call.nulls != 0;
    if (y.crashed || (query ? y.result != 0 : !(y.result < 0)) ||
        y.result != std::floor(y.result)) {
      return false;
    }
    const std::string full = std::to_string(call.values[0].i) + " " + key +
                             " " + std::to_string(int(y.result));
    if (seen_.count(full)) return true;
    const Outcome x = runner_.Execute(runner_.hwy, call);
    if (x.crashed || x.result != y.result || x.message != y.message) {
      if (differences_.insert(full).second) {
        fprintf(stderr, "%s: %.17g \"%s\", reference %.17g \"%s\": %s\n",
                r_.name.c_str(), x.result, x.message.c_str(), y.result,
                y.message.c_str(), Describe(call).c_str());
      }
      return true;
    }
    seen_.insert(full);
    std::string message = y.message;
    if (!message.empty()) message.pop_back();  // the separator
    printf("{\"%s\", \"%s\", %d, %ld, %d, 0x%llx, %d, \"%s\"},\n",
           r_.name.c_str(), Scalars(call).c_str(), call.nan_param,
           call.nan_element, call.nan_imaginary ? 1 : 0,
           static_cast<unsigned long long>(call.nulls),
           static_cast<int>(y.result), message.c_str());
    return true;
  }

 private:
  Runner& runner_;
  const Routine& r_;
  std::set<std::string> seen_, differences_;
};

// Workspace queries, with all sizes -1 and with each one alone, and as many
// null arrays as the reference accepts.
void RecordQueries(Runner& runner, Recorder& recorder, const Call& base) {
  const Routine& r = *base.routine;
  std::vector<size_t> sizes;
  for (size_t k = 0; k < r.params.size(); ++k) {
    if (r.params[k].kind == Kind::kInt &&
        r.params[k].int_class == IntClass::kWorkspace) {
      sizes.push_back(k);
    }
  }
  if (sizes.empty()) return;
  for (size_t which = 0; which <= sizes.size(); ++which) {
    Call call = base;
    for (size_t i = 0; i < sizes.size(); ++i) {
      if (which == sizes.size() || which == i) call.values[sizes[i]].i = -1;
    }
    const Outcome y = runner.Execute(runner.ref, call);
    if (y.crashed || y.result != 0) continue;
    for (size_t k = 0; k < r.params.size() && k < 64; ++k) {
      if (r.params[k].kind != Kind::kArray || r.params[k].scratch) continue;
      Call fewer = call;
      fewer.nulls |= uint64_t{1} << k;
      const Outcome z = runner.Execute(runner.ref, fewer);
      if (!z.crashed && z.result == 0) call = fewer;
    }
    if (call.nulls == 0) continue;
    recorder.Try(call, "query" + std::to_string(which) + " " +
                           std::to_string(call.nulls));
  }
}

void Record(Runner& runner, const Routine& r) {
  if (!runner.hwy.Find(r.name.c_str()) || !runner.ref.Find(r.name.c_str())) {
    return;
  }
  rng.seed(1);
  Recorder recorder(runner, r);
  for (const int layout : {LAPACK_COL_MAJOR, LAPACK_ROW_MAJOR}) {
    if (!r.has_layout && layout == LAPACK_ROW_MAJOR) break;
    for (int base = 0; base < 16; ++base) {
      Call valid{&r};
      if (!FindValid(runner, layout, valid)) continue;
      Call distinct = valid;
      DistinctLeadingDimensions(runner, distinct);
      RecordQueries(runner, recorder, distinct);
      // The largest rejected value of each leading dimension.
      for (size_t k = 0; k < r.params.size(); ++k) {
        if (r.params[k].kind != Kind::kInt ||
            r.params[k].int_class != IntClass::kLeading) {
          continue;
        }
        Call call = distinct;
        while (call.values[k].i > 0) {
          --call.values[k].i;
          if (recorder.Try(call, "ld" + std::to_string(k))) break;
        }
      }
      if (r.work_function) continue;
      // NaNs: in a whole argument, in the first and the last element of an
      // array that is checked, and in an imaginary part alone.
      for (size_t k = 0; k < r.params.size(); ++k) {
        const Param& p = r.params[k];
        const bool array = p.kind == Kind::kArray && !p.integers;
        const bool scalar = p.kind == Kind::kReal || p.kind == Kind::kComplex;
        if (!array && !scalar) continue;
        Call call = distinct;
        call.nan_param = static_cast<int>(k);
        const std::string key = "nan" + std::to_string(k);
        if (!recorder.Try(call, key)) continue;
        if (p.kind == Kind::kComplex || (array && p.parts == 2)) {
          Call imaginary = call;
          imaginary.nan_imaginary = true;
          if (array) imaginary.nan_element = 0;
          recorder.Try(imaginary, key + "i");
        }
        if (!array) continue;
        std::vector<long> detected;
        for (const long e : {0,  1,  2,  3,  4,  5,  7,  9,  11, 13,
                             16, 19, 23, 28, 34, 41, 55, 70, 90, 130}) {
          Call one = call;
          one.nan_element = e;
          const Outcome y = runner.Execute(runner.ref, one);
          if (!y.crashed && y.result < 0 && y.result == std::floor(y.result)) {
            detected.push_back(e);
          }
        }
        if (detected.empty()) continue;
        Call one = call;
        one.nan_element = detected.front();
        recorder.Try(one, key + "first");
        one.nan_element = detected.back();
        recorder.Try(one, key + "last");
      }
    }
  }
  fflush(stdout);
}

