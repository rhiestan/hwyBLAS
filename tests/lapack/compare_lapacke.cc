std::vector<Slot> Candidates(const Param& p) {
  std::vector<Slot> out;
  const auto with_i = [&out](long long i) {
    Slot s;
    s.i = i;
    out.push_back(s);
  };
  if (p.kind == Kind::kChar) {
    std::string pool = "NUTLCVASORBEPQGIDFHKXM1Z";
    std::shuffle(pool.begin(), pool.end(), rng);
    // The valid values of the usual arguments first: not every routine checks
    // them.
    static const std::map<std::string, std::string> usual = {
        {"uplo", "UL"},     {"diag", "NU"},    {"norm", "M1OIF"},
        {"trans", "NTC"},   {"transr", "NTC"}, {"side", "LR"},
        {"direct", "FB"},   {"storev", "CR"},  {"matrix_type", "GLUHBQZ"},
        {"type", "GLUHBQZ"}};
    const auto it = usual.find(p.name);
    if (it != usual.end()) {
      std::string first = it->second;
      std::shuffle(first.begin(), first.end(), rng);
      pool = first + pool;
    }
    for (const char c : pool) {
      Slot s;
      s.c = c;
      out.push_back(s);
    }
  } else if (p.kind == Kind::kReal || p.kind == Kind::kComplex) {
    std::vector<double> pool(std::begin(kReals), std::end(kReals));
    std::shuffle(pool.begin(), pool.end(), rng);
    if (p.name == "vl") pool.insert(pool.begin(), -10);
    if (p.name == "vu") pool.insert(pool.begin(), 10);
    if (p.name == "abstol") pool.insert(pool.begin(), 0);
    if (p.name == "anorm") pool.insert(pool.begin(), 3);
    if (p.name == "rcond") pool.insert(pool.begin(), -1);
    for (const double x : pool) {
      Slot s;
      s.d = x;
      s.d_imag = p.kind == Kind::kComplex ? 0.25 : 0;
      out.push_back(s);
    }
  } else if (p.int_class == IntClass::kLeading) {
    for (const int x : {16, 9, 8, 4, 1}) with_i(x);
  } else if (p.int_class == IntClass::kWorkspace) {
    for (const int x : {2048, 513, 257, 129, 65, 33, 17, 9, 5, 3, 2, 1}) {
      with_i(x);
    }
  } else {
    std::vector<int> pool = {4, 3, 5, 2, 6, 7};
    std::shuffle(pool.begin(), pool.end(), rng);
    pool.insert(pool.end(), {1, 8, 9, 0});
    if (p.name == "ilo" || p.name == "il" || p.name == "k1") {
      pool.insert(pool.begin(), 1);
    }
    if (p.name == "itype" || p.name == "incx" || p.name == "incv") {
      pool.insert(pool.begin(), 1);
    }
    for (const int x : pool) with_i(x);
  }
  return out;
}

// Changes the arguments that the reference reports until it accepts the call.
bool FindValid(Runner& runner, int layout, Call& call) {
  const Routine& r = *call.routine;
  std::vector<std::vector<Slot>> candidates(r.params.size());
  std::vector<size_t> next(r.params.size(), 1);
  call.values.assign(r.params.size(), Slot());
  call.styles.assign(r.params.size(), 0);
  call.fill_seed = rng() % 1000000;
  for (size_t k = 0; k < r.params.size(); ++k) {
    const Param& p = r.params[k];
    if (p.kind == Kind::kLayout) {
      call.values[k].i = layout;
    } else if (p.kind == Kind::kArray) {
      if (p.name == "anorm") call.styles[k] = 3;
      if (p.name == "scale" || p.name == "lscale" || p.name == "rscale") {
        call.styles[k] = 2;
      }
    } else if (p.kind != Kind::kCallback) {
      candidates[k] = Candidates(p);
      call.values[k] = candidates[k][0];
    }
  }
  for (int step = 0; step < 400; ++step) {
    const Outcome o = runner.Execute(runner.ref, call);
    if (o.crashed) return false;
    // A norm is not negative, so a negative result is an error.
    if (o.result >= 0) {
      // A numerical failure (INFO > 0): try diagonally dominant matrices.
      if (o.result > 0 && o.result == std::floor(o.result)) {
        Call dominant = call;
        for (size_t j = 0; j < r.params.size(); ++j) {
          const std::string& n = r.params[j].name;
          if (n == "a" || n == "b" || n == "ab") dominant.styles[j] = 1;
        }
        const Outcome d = runner.Execute(runner.ref, dominant);
        if (!d.crashed && d.result == 0) call = dominant;
      }
      return true;
    }
    if (o.result <= -1000) return false;
    const long k = -static_cast<long>(o.result) - 1;
    if (o.result != std::floor(o.result) || k < 0 ||
        k >= static_cast<long>(r.params.size())) {
      return false;
    }
    if (r.params[k].kind == Kind::kArray) {
      if (++call.styles[k] >= kStyles) return false;
      continue;
    }
    if (next[k] >= candidates[k].size()) return false;
    call.values[k] = candidates[k][next[k]++];
  }
  return false;
}

// Gives every leading dimension a different value, where the reference
// accepts it.
void DistinctLeadingDimensions(Runner& runner, Call& call) {
  const Routine& r = *call.routine;
  std::vector<long long> pool = {10, 11, 12, 13, 14, 15, 16, 18, 19, 20};
  std::shuffle(pool.begin(), pool.end(), rng);
  size_t used = 0;
  for (size_t k = 0; k < r.params.size(); ++k) {
    if (r.params[k].kind != Kind::kInt ||
        r.params[k].int_class != IntClass::kLeading || used >= pool.size()) {
      continue;
    }
    const long long old = call.values[k].i;
    call.values[k].i = pool[used++];
    const Outcome o = runner.Execute(runner.ref, call);
    if (o.crashed || o.result < 0) call.values[k].i = old;
  }
}

